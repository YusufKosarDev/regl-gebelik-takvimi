const { AndroidConfig, withAndroidManifest, withDangerousMod } = require('expo/config-plugins');
const fs = require('fs');
const path = require('path');

/**
 * Keeps Android from copying this app's data anywhere.
 *
 * Android backs app data up to the user's Google Drive by default, and the
 * default rules include everything: `files/` (which holds the SQLite database
 * of period records), `databases/` (AsyncStorage) and `shared_prefs/` (the
 * widget snapshot, which carries the cycle day and phase). None of that is
 * supposed to leave the phone unless the person asks for it, and the published
 * privacy policy says so.
 *
 * There are two mechanisms and both are needed:
 *
 *   - `android:allowBackup="false"` (set from app.json) turns off backup on
 *     Android 11 and below, and turns off cloud backup everywhere.
 *   - `android:dataExtractionRules` is what Android 12 and above reads. Google
 *     documents that on some manufacturers' devices `allowBackup="false"`
 *     stops the Google Drive backup but *not* the device-to-device transfer,
 *     so the rules file has to say no to that separately.
 *
 * `android:fullBackupContent` is the Android 11 and below equivalent. It is
 * redundant while `allowBackup` is false, and it is written anyway so that
 * turning `allowBackup` back on cannot quietly re-enable the old path.
 *
 * This lives in a plugin rather than in the generated manifest because
 * `expo prebuild --clean` deletes and rewrites `android/`, and an edit made by
 * hand there survives exactly until the next prebuild.
 */

const DATA_EXTRACTION_RULES = 'data_extraction_rules';
const BACKUP_RULES = 'backup_rules';

/** Android 12+. Cloud backup and device-to-device transfer are separate decisions. */
const DATA_EXTRACTION_RULES_XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-backups-disabled.js. Do not edit by hand. -->
<data-extraction-rules>
    <cloud-backup>
        <exclude domain="root" path="." />
    </cloud-backup>
    <device-transfer>
        <exclude domain="root" path="." />
    </device-transfer>
</data-extraction-rules>
`;

/** Android 11 and below. */
const BACKUP_RULES_XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-backups-disabled.js. Do not edit by hand. -->
<full-backup-content>
    <exclude domain="root" path="." />
</full-backup-content>
`;

/** Writes both rule files into res/xml, which prebuild does not create on its own. */
const withRuleFiles = (config) =>
  withDangerousMod(config, [
    'android',
    async (dangerousConfig) => {
      const xmlDir = path.join(
        dangerousConfig.modRequest.platformProjectRoot,
        'app',
        'src',
        'main',
        'res',
        'xml'
      );

      await fs.promises.mkdir(xmlDir, { recursive: true });
      await fs.promises.writeFile(
        path.join(xmlDir, `${DATA_EXTRACTION_RULES}.xml`),
        DATA_EXTRACTION_RULES_XML,
        'utf8'
      );
      await fs.promises.writeFile(
        path.join(xmlDir, `${BACKUP_RULES}.xml`),
        BACKUP_RULES_XML,
        'utf8'
      );

      return dangerousConfig;
    },
  ]);

/** Points the manifest at them. `allowBackup` itself comes from app.json. */
const withRuleAttributes = (config) =>
  withAndroidManifest(config, (manifestConfig) => {
    const application = AndroidConfig.Manifest.getMainApplicationOrThrow(
      manifestConfig.modResults
    );

    application.$['android:dataExtractionRules'] = `@xml/${DATA_EXTRACTION_RULES}`;
    application.$['android:fullBackupContent'] = `@xml/${BACKUP_RULES}`;

    return manifestConfig;
  });

module.exports = (config) => withRuleAttributes(withRuleFiles(config));
